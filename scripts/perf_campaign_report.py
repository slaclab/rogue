def load_noise_floor_parameters(path: Path) -> dict[str, Any]:
    """Read min_n, mde_z, and mde_gate_pct from Phase 1's noise-floor.json sidecar's
    `parameters` block, rather than hardcoding any of them here.

    Never raises: an unreadable file, malformed JSON, a non-mapping payload, or a missing
    `parameters` block returns the documented fallback values with `loaded` false, so this
    report still runs before or without that Phase 1 artifact -- following
    scripts/env_fingerprint.py's `_try` never-raise sentinel discipline.
    """
    result: dict[str, Any] = {
        "source_file": str(path),
        "min_n": FALLBACK_MIN_N,
        "mde_z": FALLBACK_MDE_Z,
        "mde_gate_pct": FALLBACK_MDE_GATE_PCT,
        "loaded": False,
    }
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return result
    try:
        payload = json.loads(text)
    except json.JSONDecodeError:
        return result
    if not isinstance(payload, dict):
        return result
    parameters = payload.get("parameters")
    if not isinstance(parameters, dict):
        return result
    for key in ("min_n", "mde_z", "mde_gate_pct"):
        if key in parameters:
            result[key] = parameters[key]
    result["loaded"] = True
    return result


